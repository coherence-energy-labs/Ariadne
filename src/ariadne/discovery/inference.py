@dataclass
class Evidence:
    """Container for ANY combination of available evidence on one (or several)
    putative objects. Every field is optional; the engine works with whatever
    is provided.

    Fields:
      mjd:                   epoch of the most recent observation.
      ra_deg, dec_deg:       sky position (most recent or single observation).
      rate_arcsec_hr:        on-sky angular rate, if known.
      apparent_mag:          most recent observed magnitude.
      band:                  photometric band character (g, r, i, z, V).
      band_magnitudes:       full multi-band dict (e.g. {"g":21.5, "r":20.9}).
      morphology_label:      a MorphologyClass label, if image-pipeline ran.
      morphology_confidence: associated confidence (0..1).
      n_detections:          count of independent detections.
      arc_days:              span of the arc, days.
      rms_arcsec:            orbit-fit RMS if a fit was attempted.
      orbit_state:           fitted [x,y,z,vx,vy,vz] heliocentric km/km/s.
      skybot_match_names:    SkyBoT cross-match results, empty list if checked
                              and clean, None if not checked.
      sky_context:           extra dict for any sidereal context (galactic
                              latitude, field crowding, etc.).
    """
    mjd: Optional[float] = None
    ra_deg: Optional[float] = None
    dec_deg: Optional[float] = None
    rate_arcsec_hr: Optional[float] = None
    apparent_mag: Optional[float] = None
    band: Optional[str] = None
    band_magnitudes: dict = field(default_factory=dict)
    morphology_label: Optional[str] = None
    morphology_confidence: Optional[float] = None
    n_detections: int = 1
    arc_days: float = 0.0
    rms_arcsec: Optional[float] = None
    orbit_state: Optional[list] = None
    skybot_match_names: Optional[list] = None
    sky_context: dict = field(default_factory=dict)


# ============================================================================
# Hypothesis types
# ============================================================================

@dataclass
class Hypothesis:
    """One explanation for the evidence, with priors + per-likelihood scores.

    Fields:
      label:             human-readable name (e.g. "TNO 50 AU", "NEO Apollo",
                          "satellite trail", "cosmic ray", "stellar variable").
      class_:            broad category: "moving_object", "transient", "artefact",
                          "stellar".
      orbital_class:     OrbitClass.* label if class_ == "moving_object".
      morphology_class:  MorphologyClass.* label expected.
      prior:             log p(H) -- prior probability under the population model.
      likelihood:        log p(E|H) -- how well evidence fits the hypothesis.
      free_energy:       F = -log p(H) - log p(E|H); LOWER is better.
      posterior:         p(H|E) -- normalised over the hypothesis space.
      predicted_motion_arcsec_hr:  rate this hypothesis EXPECTS.
      predicted_size_km:           rough size from magnitude + assumed albedo.
      predicted_distance_au:       rough heliocentric distance.
      explanation:       free-text 'why this hypothesis fits' for humans.
    """
    label: str
    class_: str = "unknown"
    orbital_class: Optional[str] = None
    morphology_class: Optional[str] = None
    prior: float = 0.0                  # log prior
    likelihood: float = 0.0             # log likelihood
    free_energy: float = float("inf")
    posterior: float = 0.0
    predicted_motion_arcsec_hr: Optional[float] = None
    predicted_size_km: Optional[float] = None
    predicted_distance_au: Optional[float] = None
    explanation: str = ""


@dataclass
class InferenceResult:
    """Output of one inference cycle on a piece of Evidence.

    Fields:
      hypotheses:               list of Hypothesis ordered by free_energy
                                 (best first). posterior sums to 1.
      best:                     hypothesis with highest posterior.
      entropy:                  Shannon entropy of the posterior (high =
                                 ambiguous; low = confident).
      recommended_followup:     dict {action, observation_target, expected_info_gain}
      memory_matches:           list of Candidate from the store that resemble
                                 this evidence (episodic recall).
      pareto_front:             multi-objective optimal hypotheses (probability,
                                 novelty, low follow-up cost).
      narrative:                human-readable summary of the inference.
    """
    hypotheses: list
    best: Optional[Hypothesis] = None
    entropy: float = float("inf")
    recommended_followup: dict = field(default_factory=dict)
    memory_matches: list = field(default_factory=list)
    pareto_front: list = field(default_factory=list)
    narrative: str = ""


