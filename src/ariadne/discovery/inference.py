# Hypothesis generation (over moving-object classes + artefact classes)
# ============================================================================

def _generate_moving_object_hypotheses(evidence: Evidence,
                                       class_priors: dict) -> list[Hypothesis]:
    """One hypothesis per orbital class (NEO/MBA/Trojan/Centaur/TNO/etc.)."""
    hyps = []
    for class_name, prior_frac in class_priors.items():
        prior = math.log(max(prior_frac, 1e-9))
        likelihood = 0.0
        n_terms = 0

        if evidence.rate_arcsec_hr is not None:
            likelihood += _rate_log_likelihood(evidence.rate_arcsec_hr, class_name)
            n_terms += 1

        dist = TYPICAL_DISTANCES.get(class_name, 5.0)
        if evidence.apparent_mag is not None:
            likelihood += _magnitude_log_likelihood(
                evidence.apparent_mag, class_name, dist)
            n_terms += 1

        if evidence.morphology_label is not None:
            likelihood += _morphology_log_likelihood(
                evidence.morphology_label,
                evidence.morphology_confidence or 0.5,
                "POINT",
            )
            n_terms += 1

        if evidence.orbit_state is not None:
            likelihood += _orbit_state_log_likelihood(
                evidence.orbit_state, class_name)
            n_terms += 1

        # If SkyBoT confirmed clean (empty list), bump prior slightly for
        # rare classes (TNO finds + comet discoveries are the prize).
        if evidence.skybot_match_names is not None and not evidence.skybot_match_names:
            if class_name in ("SEDNOID", "DETACHED", "RESONANT_KBO",
                              "COMET_HYPERBOLIC"):
                prior += math.log(2.0)

        # If a strong RMS fit exists, weight likelihood up
        if evidence.rms_arcsec is not None and math.isfinite(evidence.rms_arcsec):
            if evidence.rms_arcsec < 3.0:
                likelihood += math.log(2.0)
            elif evidence.rms_arcsec > 15.0:
                likelihood += math.log(0.5)
        # NOTE: do NOT normalise likelihood by sqrt(n_terms): more evidence
        # should accumulate MORE log-likelihood. Normalising hides discriminating
        # power (a strict rate mismatch deserves a strong penalty regardless of
        # how many other evidence terms exist).

        rate_lo, rate_hi = EXPECTED_RATES.get(class_name, (0, 10))
        hyps.append(Hypothesis(
            label=f"{class_name} ({dist:.0f} AU)",
            class_="moving_object",
            orbital_class=class_name,
            morphology_class="POINT",
            prior=prior,
            likelihood=likelihood,
            free_energy=-(prior + likelihood),
            predicted_motion_arcsec_hr=(rate_lo + rate_hi) / 2.0,
            predicted_distance_au=dist,
            predicted_size_km=_size_from_magnitude(evidence.apparent_mag, dist)
                              if evidence.apparent_mag else None,
            explanation=(f"Class {class_name}: prior {prior_frac*100:.2f}%, "
                          f"expected rate {rate_lo}-{rate_hi} arcsec/hr at "
                          f"{dist} AU."),
        ))
    return hyps


def _generate_artefact_hypotheses(evidence: Evidence,
                                  artefact_priors: dict) -> list[Hypothesis]:
    """One hypothesis per artefact category.

    Artefacts have STRONG anti-evidence rules: a multi-night arc with low RMS
    and many independent re-detections cannot physically be a cosmic ray,
    subtraction residual, or single-image artefact. The likelihood includes
    those penalties so the engine ranks artefacts correctly even when no
    positive evidence (morphology label, extreme rate) is present.
    """
    hyps = []

    # GLOBAL anti-evidence: NO artefact class in this set produces a coherent
    # multi-night moving arc. A long-baseline arc with low RMS and consistent
    # proper motion EXCLUDES every spurious class.
    single_image_penalty = 0.0     # penalty for single-frame artefacts only
    if evidence.n_detections >= 3:
        single_image_penalty -= 2.0 * (evidence.n_detections - 2)
    if evidence.arc_days >= 3.0:
        single_image_penalty -= 1.0 * min(evidence.arc_days / 3.0, 5.0)
    if (evidence.rms_arcsec is not None and math.isfinite(evidence.rms_arcsec)
            and evidence.rms_arcsec < 5.0 and evidence.n_detections >= 4):
        single_image_penalty -= 3.0

    # NONE of the artefact classes naturally generate consistent multi-night
    # proper motion. If the evidence shows >0.2"/hr motion across >=3 detections,
    # penalize every artefact heavily.
    multinight_motion_penalty = 0.0
    if (evidence.rate_arcsec_hr is not None and evidence.rate_arcsec_hr > 0.2
            and evidence.n_detections >= 3 and evidence.arc_days >= 1.0):
        multinight_motion_penalty -= 3.0 * min(evidence.n_detections, 8) / 4.0
        if (evidence.rms_arcsec is not None and evidence.rms_arcsec < 3.0):
            multinight_motion_penalty -= 4.0

    for label, prior_frac in artefact_priors.items():
        prior = math.log(max(prior_frac, 1e-9))
        likelihood = multinight_motion_penalty
        explanation = f"Artefact class {label}, prior {prior_frac*100:.1f}%."

        # Single-frame artefacts also get the n_detections penalty
        if label in ("cosmic_ray", "subtraction_residual", "edge_artefact",
                     "ghost_or_diffraction"):
            likelihood += single_image_penalty

        # cosmic_ray: strong likelihood if morphology says so + low rate
        if label == "cosmic_ray":
            if evidence.morphology_label == "COSMIC_RAY":
                likelihood += math.log(0.9 * (evidence.morphology_confidence or 0.5))
            elif evidence.morphology_label == "POINT":
                likelihood += math.log(0.05)
            if evidence.n_detections == 1:
                likelihood += math.log(2.0)        # cosmic rays don't repeat

        # satellite_trail: VERY high rate + 1-night
        elif label == "satellite_trail":
            if evidence.rate_arcsec_hr is not None and evidence.rate_arcsec_hr > 1000:
                likelihood += math.log(0.9)
            if evidence.morphology_label == "STREAK":
                likelihood += math.log(0.95 * (evidence.morphology_confidence or 0.5))

        # stellar_variable: zero motion + position matches a known star catalogue
        elif label == "stellar_variable":
            if evidence.rate_arcsec_hr is not None and evidence.rate_arcsec_hr < 0.05:
                likelihood += math.log(0.8)
            else:
                likelihood += math.log(0.05)

        # supernova_or_agn: zero motion + galaxy-class position
        elif label == "supernova_or_agn":
            if evidence.rate_arcsec_hr is not None and evidence.rate_arcsec_hr < 0.05:
                likelihood += math.log(0.5)
            if evidence.morphology_label == "EXTENDED":
                likelihood += math.log(0.8)
            else:
                likelihood += math.log(0.1)

        # subtraction_residual: dipole-like patterns -> high RMS, low n_detections
        elif label == "subtraction_residual":
            if evidence.n_detections == 1:
                likelihood += math.log(0.5)
            if evidence.rms_arcsec is not None and evidence.rms_arcsec > 20:
                likelihood += math.log(0.7)

        # edge_artefact: morphology says so
        elif label == "edge_artefact":
            if evidence.morphology_label == "EDGE_ARTEFACT":
                likelihood += math.log(0.95 * (evidence.morphology_confidence or 0.5))

        # blend_two_stars: morphology BLEND + zero motion
        elif label == "blend_two_stars":
            if evidence.morphology_label == "BLEND":
                likelihood += math.log(0.5)
            if evidence.rate_arcsec_hr is not None and evidence.rate_arcsec_hr < 0.1:
                likelihood += math.log(0.7)

        else:
            # generic artefact prior, no evidence-specific boost. Use += so the
            # multinight_motion_penalty already accumulated stays in effect.
            likelihood += math.log(0.2)

        hyps.append(Hypothesis(
            label=label, class_="artefact",
            prior=prior, likelihood=likelihood,
            free_energy=-(prior + likelihood),
            explanation=explanation,
        ))
    return hyps


def _size_from_magnitude(V_mag: float, distance_au: float,
                         albedo: float = 0.10) -> float:
    """Rough size estimate (km) from apparent magnitude assuming a typical albedo.

    H = V - 5 log10(r * delta) + correction; here we collapse to r ~ delta and
    use the standard D = 1329 / sqrt(albedo) * 10^(-0.2 H) kilometres.
    """
    if V_mag is None or not math.isfinite(V_mag) or distance_au <= 0:
        return float("nan")
    # absolute mag H -- delta = r at opposition, near-circular geometry
    H = V_mag - 5 * math.log10(distance_au) - 5 * math.log10(distance_au - 1.0
                                                              if distance_au > 1 else 1)
    D_km = 1329.0 / math.sqrt(max(albedo, 0.02)) * 10 ** (-0.2 * H)
    return D_km


# ============================================================================
# Posterior normalisation, entropy, narrative
# ============================================================================

def _normalise_posterior(hypotheses: list[Hypothesis]):
    """Convert free-energy values to a normalised posterior distribution.

    Uses softmax(-F) for numerical stability against very wide free-energy ranges.
    """
    if not hypotheses:
        return
    # subtract the min so the largest -F is 0 (stability)
    min_F = min(h.free_energy for h in hypotheses if math.isfinite(h.free_energy))
    weights = []
    for h in hypotheses:
        if not math.isfinite(h.free_energy):
            weights.append(0.0)
        else:
            weights.append(math.exp(-(h.free_energy - min_F)))
    total = sum(weights)
    if total <= 0:
        for h in hypotheses:
            h.posterior = 1.0 / len(hypotheses)
        return
    for h, w in zip(hypotheses, weights):
        h.posterior = w / total


def _shannon_entropy(probs: list[float]) -> float:
    """H = -sum p_i log p_i in nats."""
    s = 0.0
    for p in probs:
        if p > 0:
            s -= p * math.log(p)
    return s


def _build_narrative(result: InferenceResult, evidence: Evidence) -> str:
    """Produce a human-readable summary of the inference."""
    if not result.hypotheses:
        return "No hypotheses generated."
    best = result.best
    second = result.hypotheses[1] if len(result.hypotheses) > 1 else None

    lines = []
    if best.posterior > 0.6:
        lines.append(f"HIGH-CONFIDENCE: {best.label} ({best.posterior*100:.0f}%).")
    elif best.posterior > 0.35:
        lines.append(f"LEADING HYPOTHESIS: {best.label} ({best.posterior*100:.0f}%); "
                     f"runner-up {second.label if second else 'n/a'} "
                     f"({second.posterior*100:.0f}% if second else 0).")
    else:
        lines.append(f"AMBIGUOUS: top guess {best.label} only "
                     f"{best.posterior*100:.0f}%; evidence is sparse "
                     f"(entropy {result.entropy:.2f} nats).")

    # Evidence summary
    parts = []
    if evidence.rate_arcsec_hr is not None:
        parts.append(f"rate {evidence.rate_arcsec_hr:.2f}\"/hr")
    if evidence.apparent_mag is not None:
        parts.append(f"mag {evidence.apparent_mag:.1f}")
    if evidence.morphology_label is not None:
        parts.append(f"morph {evidence.morphology_label}")
    if evidence.skybot_match_names is not None and not evidence.skybot_match_names:
        parts.append("no SkyBoT match")
    if evidence.n_detections > 1:
        parts.append(f"{evidence.n_detections} detections over {evidence.arc_days:.1f}d")
    if parts:
        lines.append(f"  Evidence: {', '.join(parts)}.")

    # Top-3 ranking
    lines.append(f"  Top hypotheses:")
    for h in result.hypotheses[:3]:
        lines.append(f"    {h.posterior*100:>5.1f}%  {h.label:<28s}  ({h.explanation[:64]})")

    if result.recommended_followup:
        f = result.recommended_followup
        lines.append(f"  Recommended follow-up: {f.get('action', '?')} "
                     f"-> {f.get('reason', '')}")

    if result.memory_matches:
        n = len(result.memory_matches)
        lines.append(f"  Episodic recall: {n} similar past candidate(s) in store.")

    return "\n".join(lines)


def _episodic_recall(evidence: Evidence, store: CandidateStore,
                     max_matches: int = 5,
                     sky_tol_arcmin: float = 60.0,
                     rate_tol_arcsec_hr: float = 1.0) -> list[Candidate]:
    """Search the candidate store for prior detections similar to this evidence."""
    if store is None or evidence.ra_deg is None or evidence.dec_deg is None:
        return []
    matches = []
    for c in store:
        dra = (c.ra - evidence.ra_deg) * math.cos(math.radians(evidence.dec_deg))
        ddec = c.dec - evidence.dec_deg
        sep_arcmin = math.hypot(dra, ddec) * 60.0
        if sep_arcmin > sky_tol_arcmin:
            continue
        if evidence.rate_arcsec_hr is not None:
            if abs(c.rate_arcsec_hr - evidence.rate_arcsec_hr) > rate_tol_arcsec_hr:
                continue
        matches.append((sep_arcmin, c))
    matches.sort(key=lambda x: x[0])
    return [m[1] for m in matches[:max_matches]]


def _pareto_front(hypotheses: list[Hypothesis]) -> list[Hypothesis]:
    """Return the Pareto-optimal hypotheses on (posterior, novelty) axes.

    novelty = -log(prior) (rare populations score higher).
    A hypothesis is dominated if there exists another with higher posterior
    AND higher novelty.
    """
    items = []
    for h in hypotheses:
        novelty = -h.prior
        items.append((h, h.posterior, novelty))
    front = []
    for h, p, n in items:
        dominated = False
        for h2, p2, n2 in items:
            if h is h2:
                continue
            if p2 >= p and n2 >= n and (p2 > p or n2 > n):
                dominated = True
                break
        if not dominated:
            front.append(h)
    front.sort(key=lambda h: h.posterior, reverse=True)
    return front


def _recommend_followup(result: InferenceResult,
                        evidence: Evidence) -> dict:
    """Recommend the NEXT observation that would maximally reduce uncertainty.

    Heuristics:
      - High entropy (>1.5 nats): take a 2nd-night confirmation observation.
      - Top hypothesis is high-novelty (rare class): submit to MPC + alert.
      - Top hypothesis is artefact: tag as bogus, no follow-up.
      - Mid-entropy: take a multi-band photometric observation to constrain
        the color-based classification.
    """
    if not result.hypotheses:
        return {"action": "no_action", "reason": "no hypotheses"}
    best = result.best
    entropy = result.entropy

    if best.class_ == "artefact":
        return {
            "action": "discard",
            "reason": f"top hypothesis is {best.label} (artefact); not worth follow-up",
            "expected_info_gain_nats": 0.0,
        }

    if entropy > 1.5:
        return {
            "action": "observe_second_night",
            "reason": (f"posterior is ambiguous (entropy {entropy:.2f} nats); "
                       f"a second-night detection would constrain the orbit"),
            "expected_info_gain_nats": min(entropy, 2.0),
            "observation_target": {
                "ra_deg": evidence.ra_deg,
                "dec_deg": evidence.dec_deg,
                "expected_rate_arcsec_hr": best.predicted_motion_arcsec_hr,
                "expected_displacement_arcmin_per_day": (
                    best.predicted_motion_arcsec_hr * 24.0 / 60.0
                    if best.predicted_motion_arcsec_hr else None),
            },
        }

    if best.class_ == "moving_object" and best.orbital_class in (
            "SEDNOID", "DETACHED", "RESONANT_KBO", "COMET_HYPERBOLIC"):
        return {
            "action": "alert_and_submit_mpc",
            "reason": f"high-novelty {best.orbital_class} candidate at {best.posterior*100:.0f}%",
            "expected_info_gain_nats": entropy,
        }

    if 0.5 < entropy <= 1.5 and not evidence.band_magnitudes:
        return {
            "action": "observe_multiband",
            "reason": ("posterior is moderately confident; multi-band photometry "
                       "would constrain compositional class"),
            "expected_info_gain_nats": entropy * 0.5,
            "observation_target": {
                "ra_deg": evidence.ra_deg,
                "dec_deg": evidence.dec_deg,
                "bands_needed": ["g", "r", "i", "z"],
            },
        }

    return {
        "action": "monitor",
        "reason": f"sufficient confidence ({best.posterior*100:.0f}%) on {best.label}",
        "expected_info_gain_nats": entropy * 0.1,
    }


