"""Seeded replay that PRODUCES every number cited in ONE_FRONTIER_INTEGRATION.md.

The integration document carries no hand-copied numbers: its evidence block is
rendered from ``docs/one_frontier_replay.json``, which this script writes.

    python scripts/one_frontier_replay.py                 # run all, write JSON + doc block
    python scripts/one_frontier_replay.py --check         # re-run deterministic sections
                                                          # and compare with the JSON
    python scripts/one_frontier_replay.py --render-only   # re-render the doc from the JSON

Determinism: every random draw comes from a fixed ``numpy.random.default_rng`` seed,
so test counts, mutant verdicts and simulated trajectory counts are reproducible
exactly. Floating-point discrepancy maxima depend on the BLAS/LAPACK build and are
checked against their declared ceilings, not bit-for-bit. Timings are MEASURED on the
recording machine and are never compared by ``--check``.
"""

